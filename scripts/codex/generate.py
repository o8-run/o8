#!/usr/bin/env python3
"""Generate the stdio transport types from the pinned Apache-2.0 Codex schemas."""
import json
from pathlib import Path
root = Path(__file__).resolve().parents[2]
lines = ['// Generated by scripts/codex/generate.py. Do not edit.', '// Source: openai/codex rust-v0.170.0, codex-rs/app-server-protocol/schema/json/', '// Apache-2.0; see licenses/codex-Apache-2.0.txt and codex-NOTICE.txt.', 'use serde::{Deserialize, Serialize};', 'use serde_json::Value;', '#[derive(Clone, Debug, Serialize, Deserialize, PartialEq, Eq)]', '#[serde(untagged)]', 'pub enum RequestId { String(String), Integer(i64) }']
for name in ['JSONRPCRequest', 'JSONRPCNotification', 'JSONRPCResponse', 'JSONRPCError']:
    schema = json.loads((root / 'schemas/codex' / (name+'.json')).read_text())
    lines += ['#[derive(Clone, Debug, Serialize, Deserialize)]', 'pub struct '+name+' {']
    for key, prop in schema['properties'].items():
        ty = 'String' if isinstance(prop, dict) and prop.get('type') == 'string' else 'RequestId' if isinstance(prop, dict) and prop.get('$ref') == '#/definitions/RequestId' else 'Value'
        if key not in schema.get('required', []):
            lines += ['    #[serde(default, skip_serializing_if = "Option::is_none")]']
            ty = 'Option<'+ty+'>'
        lines += ['    pub '+key+': '+ty+',']
    lines += ['}']
(root / 'crates/o8d/src/codex/generated.rs').write_text('\n'.join(lines)+'\n')
